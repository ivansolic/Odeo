#!/usr/bin/env bash
#
# gen-legacy-hashes.sh, build the list scripts/odeo-migrate-legacy.sh recognises Odeo's own
# copies by. Maintainer tooling: repo-only, because it needs this repository's git history,
# which a plugin install does not have; the list it writes ships in scripts/.
#
# The list holds one line per distinct <kind> <name> <sha256>: every version of
# skills/<name>/SKILL.md ("skill") and agents/<name>.md ("agent", plus docs/agent-rubric.md,
# which install.sh also placed under agents/) that exists anywhere in git history, across ALL
# refs (tags such as dev-phase-archive and the published snapshot branches included), plus the
# copies in the working tree right now. install.sh copied whatever was in the clone at that
# moment, so any version Odeo ever committed is a version a user may still have installed.
# Name-bound pairs, not a bare set of hashes: a skill is recognised only under the name it
# was shipped as.
#
# Re-run it after ANY edit to a shipped skill or agent, and commit the result with the edit:
# .claude/maintainer/tests/legacy-hashes.test.sh turns RED while the list lacks a version.
#
# Usage:   gen-legacy-hashes.sh            print the list on stdout
#          gen-legacy-hashes.sh --write    rewrite scripts/odeo-legacy-hashes.txt in place
# Exit:    0 ok · 1 git or hashing failed (nothing written) · 2 usage, or a shallow clone
# Needs:   git, awk, sort and shasum (macOS) or sha256sum. Portable to bash 3.2.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
LIST_REL="scripts/odeo-legacy-hashes.txt"
NAME='[a-z0-9][a-z0-9-]*'

WRITE=false
case "${1:-}" in
  "") ;;
  --write) WRITE=true ;;
  *) echo "usage: gen-legacy-hashes.sh [--write]" >&2; exit 2 ;;
esac
[ "$#" -le 1 ] || { echo "usage: gen-legacy-hashes.sh [--write]" >&2; exit 2; }

if command -v shasum >/dev/null 2>&1; then
  sha256_stdin() { shasum -a 256 | awk '{print $1}'; }
elif command -v sha256sum >/dev/null 2>&1; then
  sha256_stdin() { sha256sum | awk '{print $1}'; }
else
  echo "gen-legacy-hashes: neither shasum nor sha256sum found." >&2; exit 1
fi

# A shallow clone has only part of the history, so the list would silently miss versions.
if [ "$(git -C "$REPO" rev-parse --is-shallow-repository 2>/dev/null)" != "false" ]; then
  echo "gen-legacy-hashes: this clone is shallow (or not a git repository); the history is incomplete." >&2
  exit 2
fi

# to_pair <path>: prints "<kind> <name>" for a shipped path, nothing for any other path
to_pair() {
  printf '%s\n' "$1" | awk -v n="$NAME" '
    $0 ~ "^skills/" n "/SKILL\\.md$" { split($0, a, "/"); print "skill " a[2]; next }
    $0 ~ "^agents/" n "\\.md$"       { sub(/^agents\//, ""); sub(/\.md$/, ""); print "agent " $0; next }
    $0 == "docs/agent-rubric.md"     { print "agent agent-rubric" }'
}

tmp="$(mktemp -d)" || exit 1
trap 'rm -rf "$tmp"' EXIT

# 1) every blob ever committed at a shipped path, across all refs. --raw gives "<mode> <mode>
#    <old> <new> <status>\t<path>"; -m also covers merge commits; --no-renames keeps each path
#    as an add/modify; a symlink (mode 120000) holds a target, not content, so it is skipped.
git -C "$REPO" log --all -m --format= --raw --no-abbrev --no-renames --diff-filter=AM \
    -- 'skills/*/SKILL.md' 'agents/*.md' 'docs/agent-rubric.md' > "$tmp/raw" \
  || { echo "gen-legacy-hashes: git log failed." >&2; exit 1; }
while IFS="$(printf '\t')" read -r meta path; do
  set -- $meta
  [ "$2" = "120000" ] && continue
  pair="$(to_pair "$path")"
  [ -n "$pair" ] && printf '%s %s\n' "$pair" "$4"
done < "$tmp/raw" | LC_ALL=C sort -u > "$tmp/blobs"

# 2) hash each distinct blob's content
: > "$tmp/hashes"
while read -r kind name blob; do
  h="$(git -C "$REPO" cat-file blob "$blob" | sha256_stdin)"
  [ "${#h}" -eq 64 ] || { echo "gen-legacy-hashes: could not hash blob $blob ($kind $name)." >&2; exit 1; }
  printf '%s %s %s\n' "$kind" "$name" "$h" >> "$tmp/hashes"
done < "$tmp/blobs"

# 3) the copies in the working tree right now (what this checkout would ship)
for f in "$REPO"/skills/*/SKILL.md "$REPO"/agents/*.md "$REPO/docs/agent-rubric.md"; do
  [ -f "$f" ] || continue
  rel="${f#"$REPO"/}"; pair="$(to_pair "$rel")"
  [ -n "$pair" ] || { echo "gen-legacy-hashes: skipping $rel (name is not a lowercase slug)." >&2; continue; }
  printf '%s %s\n' "$pair" "$(sha256_stdin < "$f")" >> "$tmp/hashes"
done

{
  echo "# Every skill and agent file Odeo has shipped, as: <kind> <name> <sha256 of the file>."
  echo "# odeo-migrate-legacy.sh moves an old install.sh copy aside only when its name AND content match a line here."
  echo "# Generated by the maintainer tooling from git history; do not edit by hand."
  LC_ALL=C sort -u "$tmp/hashes"
} > "$tmp/out"

if $WRITE; then
  mkdir -p "$(dirname "$REPO/$LIST_REL")" && cp "$tmp/out" "$REPO/$LIST_REL" || { echo "gen-legacy-hashes: could not write $LIST_REL." >&2; exit 1; }
  echo "gen-legacy-hashes: wrote $LIST_REL ($(grep -vc '^#' "$tmp/out") entries)." >&2
else
  cat "$tmp/out"
fi
